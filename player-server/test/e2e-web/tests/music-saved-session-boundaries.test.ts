import { readFileSync } from 'node:fs';
import { test, expect } from '@playwright/test';
import { Evidence, loadFixture } from './helpers/music-fixture';
import { keyboardLogin, audioState, openQueueMoreAction} from './helpers/music-ui';

test.skip(!process.env.PLAYER_MUSIC_FIXTURE || !process.env.PLAYER_NATIVE_SESSION, 'Requires completed native M17 saved-session evidence and prepared viewer ACL queue');
test('M17 native-to-browser continuation and live revoked-media revalidation', async ({ page, browser }, info) => {
  const fixture = loadFixture();
  const evidence = new Evidence(fixture.evidenceDir, info.project.name, { browser_version: browser.version(), server_build: fixture.buildRevision });
  const records = JSON.parse(readFileSync(process.env.PLAYER_NATIVE_SESSION!, 'utf8'));
  const expected = records.findLast((row: any) => row.scenario === 'Native Replace saves current ordered queue for browser continuation').saved;
  const queue = () => page.evaluate(async () => (await import('/js/queue.js')).queueState());
  const panel = page.locator('#queue-panel');
  await keyboardLogin(page, fixture.admin);
  const remote = await (await page.request.get('/api/v1/queue')).json();
  expect(remote.entries).toEqual(expected.entries);
  expect(remote.current_id).toBe(expected.current_id);
  expect(remote.position_seconds).toBeCloseTo(expected.position_seconds, 1);
  await page.keyboard.press('Q');
  await openQueueMoreAction(page, 'Continue session');
  await expect(panel.getByRole('button', { name: 'Resume queue', exact: true })).toBeVisible();
  const transferred = await queue();
  expect(transferred.entries.map((entry: any) => entry.id)).toEqual(expected.entries.map((entry: any) => entry.id));
  expect(transferred.entries[transferred.index].id).toBe(expected.current_id);
  expect(transferred.position).toBeCloseTo(expected.position_seconds, 1);
  expect((await audioState(page)).paused).toBe(true);
  await page.keyboard.press('Escape');
  await page.getByRole('button', { name: 'Log out', exact: true }).click();
  await keyboardLogin(page, fixture.user);
  const aclRemote = await (await page.request.get('/api/v1/queue')).json();
  expect(aclRemote.entries.map((entry: any) => entry.id)).toEqual([101, 102, 103]);
  await page.keyboard.press('Q');
  page.once('dialog', dialog => dialog.accept());
  await openQueueMoreAction(page, 'Continue session');
  await expect(panel.getByRole('button', { name: 'Resume queue', exact: true })).toBeVisible();
  const filtered = await queue();
  expect(filtered.entries.map((entry: any) => entry.id)).toEqual([101, 103]);
  expect(filtered.position).toBe(0);
  expect((await audioState(page)).paused).toBe(true);
  expect((await (await page.request.get('/api/v1/queue')).json()).revision).toBe(aclRemote.revision);
  const screenshot = evidence.path('m17-native-transfer-and-acl.png');
  await page.screenshot({ path: screenshot, animations: 'disabled' });
  evidence.record({ feature: 'M17', scenario: 'native saved queue continues exactly in browser; revoked current occurrence filtered against live permissions without autoplay or overwriting server', result: 'pass', data: { expected, transferred, filtered }, artifacts: [screenshot] });
});
