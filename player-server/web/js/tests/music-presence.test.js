import assert from 'node:assert/strict';
import { createMusicPresence } from '../music-presence-controller.js';
let view, pending, fail = false, snapshot = {media_id:1,state:'playing',position_seconds:20};
const calls = [];
const controller = createMusicPresence({ clientID:'test-client-12345678', snapshot:()=>snapshot, render:v=>{view=v;}, request: async(method,user,body)=>{
 calls.push({method,user,body});
 if (fail) throw Error('offline');
 if (method==='GET') return pending ? new Promise(resolve=>{pending=resolve;}) : [{title:'Private',username:'One'}];
 return null;
}});
const tick = () => new Promise(resolve=>setImmediate(resolve));
controller.setAccount(1); await controller.refresh();
assert.equal(view.sharing,false);assert.equal(calls.length,0,'off/collapsed sends no listener requests');
controller.setOpen(true);await tick();assert.equal(view.rows[0].title,'Private');
assert.equal(calls.filter(c=>c.method==='PUT').length,0,'viewing does not share');
controller.setSharing(true);await tick();assert.equal(calls.at(-2).method,'PUT');
assert.equal(calls.at(-2).body.state,'playing');
snapshot={...snapshot,state:'paused',position_seconds:45};await controller.refresh();
assert.equal(calls.filter(c=>c.method==='PUT').at(-1).body.position_seconds,45);
controller.setSharing(false);await tick();
assert.equal(calls.filter(c=>c.method==='DELETE').length,1);
assert.ok(calls.filter(c=>c.method==='DELETE').at(-1).body.sequence>calls.filter(c=>c.method==='PUT').at(-1).body.sequence);
pending=true;const work=controller.refresh();await tick();
controller.setAccount(2);assert.equal(view.rows.length,0);assert.equal(view.sharing,false);
pending([{title:'Old account'}]);pending=null;await work;
assert.equal(view.rows.length,0,'account changes reject stale private response');
await controller.refresh();assert.equal(view.rows[0].title,'Private');
fail=true;await controller.refresh();assert.equal(view.rows.length,0);assert.match(view.message,/unavailable/);
controller.clear();assert.equal(view.rows.length,0);
console.log('music presence privacy controller PASS');
