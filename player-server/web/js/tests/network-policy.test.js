import assert from 'node:assert/strict';
import { detectedNetwork, musicNetwork, networkQuality, musicPrefetchAllowed, musicSessionSyncAllowed, assertMusicStreamingAllowed, saveNetworkPreferences, MusicNetworkRestricted } from '../network-policy.js';
const values=new Map();
globalThis.localStorage={getItem:key=>values.get(key)||null,setItem:(key,value)=>values.set(key,value)};
Object.defineProperty(globalThis,'navigator',{value:{connection:{effectiveType:'4g'}},configurable:true});
assert.equal(detectedNetwork(),'unknown','4g is a speed classification, not bearer evidence');
assert.equal(detectedNetwork({connection:{type:'wifi'}}),'wifi');
assert.equal(detectedNetwork({connection:{type:'ethernet'}}),'wifi');
assert.equal(detectedNetwork({connection:{type:'cellular'}}),'mobile');
saveNetworkPreferences({wifiQuality:'original',mobileQuality:'opus96',streamWifiOnly:true,syncWifiOnly:true});
assert.equal(musicNetwork(),'unknown');
assert.equal(networkQuality('auto'),'opus96');
assert.equal(musicPrefetchAllowed(),false);
assert.equal(musicSessionSyncAllowed(),false);
assert.throws(()=>assertMusicStreamingAllowed({type:'audio'}),MusicNetworkRestricted);
assert.doesNotThrow(()=>assertMusicStreamingAllowed({type:'video'}));
saveNetworkPreferences({mode:'wifi'});
assert.equal(networkQuality('auto'),'original');
assert.equal(musicPrefetchAllowed(),true);
assert.equal(musicSessionSyncAllowed(),true);
assert.doesNotThrow(()=>assertMusicStreamingAllowed({type:'audio'}));
saveNetworkPreferences({mode:'mobile',streamWifiOnly:false,mobilePrefetch:true});
assert.equal(musicPrefetchAllowed(),true);
console.log('Music network bearer/fallback and restriction tests passed.');

// Policy holds the transfer, never the durable local mutation.
const { SavedQueueSync } = await import('../queue-sync.js');
let requests=0;
const storage={getItem:key=>values.get(key)||null,setItem:(key,value)=>values.set(key,value)};
const session=new SavedQueueSync({storage,request:async method=>{requests++;return method==='GET'?{revision:0}:{conflict:false,queue:{revision:1}};}});
session.bind('session');
const snapshot={entries:[],current_id:0,position_seconds:0};
globalThis.crypto ??= (await import('node:crypto')).webcrypto;
session.capture(snapshot);
await session.sync();
assert.equal(requests,0);
assert(session.state.pending);
const restored=new SavedQueueSync({storage,request:session.request});restored.bind('session');
assert(restored.state.pending,'blocked edits survive a fresh sync object');
assert.equal(await restored.refresh(),null);
assert.match(restored.message,/Continue session waits for Wi-Fi/);
saveNetworkPreferences({mode:'wifi'});
await restored.sync();
assert.equal(requests,2);
assert.equal(restored.state.pending,null);
console.log('Saved music session restrictions preserve edits and resume on Wi-Fi.');
