import assert from 'node:assert/strict';
import { API } from '../api.js';
import { setPodcastAccount } from '../podcast-episode-state.js';
const events = new EventTarget();
globalThis.document = events;
globalThis.CustomEvent ??= class extends Event { constructor(name, options) { super(name); this.detail=options.detail; } };
const {podcastDownloading,downloadPodcastEpisode,cancelPodcastDownload}=await import('../podcast-downloads.js');
setPodcastAccount(9);
let requests=0,signal,release;
API.downloadEpisode=async(id,options)=>{requests++;signal=options.signal;return new Promise((resolve,reject)=>{
 release=resolve;signal.addEventListener('abort',()=>reject(new DOMException('cancelled','AbortError')));
});};
const first=downloadPodcastEpisode(7);
assert.equal(podcastDownloading(7),true);
assert.equal(downloadPodcastEpisode(7),first,'rerender joins same transfer');
await Promise.resolve();
assert.equal(requests,1);
cancelPodcastDownload(8);
assert.equal(signal.aborted,false,'unrelated episode cannot cancel transfer');
cancelPodcastDownload(7);
await assert.rejects(first,{name:'AbortError'});
assert.equal(podcastDownloading(7),false,'cancel settles and permits retry');
const retry=downloadPodcastEpisode(7);await Promise.resolve();release({id:42});
assert.deepEqual(await retry,{id:42});assert.equal(podcastDownloading(7),false);
const changing=downloadPodcastEpisode(7);await Promise.resolve();
setPodcastAccount(10);events.dispatchEvent(new Event('podcast:account-changed'));
await assert.rejects(changing,{name:'AbortError'});
assert.equal(podcastDownloading(7),false,'account change aborts former transfer');
console.log('Podcast transfer cancellation, retry and account ownership passed.');
