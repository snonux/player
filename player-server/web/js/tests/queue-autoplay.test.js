import assert from 'node:assert/strict';
import { QueueAutoplay } from '../queue-autoplay.js';
const policy = new QueueAutoplay();
let calls = 0;
const args = { seedId: 1, excluded: [1, 2], current: () => true,
 fetch: async () => { calls++; return [1,2,3,3,4].map(id => ({song:{id,type:'audio'}})); } };
assert.equal(await policy.resolve(args), null);
assert.equal(calls, 0);
policy.setEnabled(true);
assert.deepEqual((await policy.resolve(args)).map(s => s.id), [3,4]);
assert.equal(policy.loading, false);
assert.deepEqual(await policy.resolve({...args, online:false}), []);
assert.equal(calls, 1);
assert.match(policy.status, /connection/);
assert.deepEqual(await policy.resolve({...args, fetch:async()=>[]}), []);
assert.equal(policy.status, 'No additional related suggestions.');
assert.deepEqual(await policy.resolve({...args, fetch:async()=>{throw Error('offline');}}), []);
assert.match(policy.status, /Could not load/);
let release;
const pending = policy.resolve({...args, fetch:()=>new Promise(resolve=>{release=resolve;})});
assert.equal(policy.loading, true);
assert.equal(await policy.resolve(args), null, 'only one lookup may run');
policy.setEnabled(false);
release([{song:{id:5,type:'audio'}}]);
assert.equal(await pending, null, 'disable cancels late results');
assert.equal(policy.loading, false);
policy.setEnabled(true);
let current=true;
const moved=policy.resolve({...args,current:()=>current,fetch:()=>new Promise(resolve=>{release=resolve;})});
current=false;release([{song:{id:5,type:'audio'}}]);
assert.equal(await moved,null,'actor ownership change cancels late results');
assert.equal((await policy.resolve({...args,fetch:async()=>Array.from({length:30},(_,i)=>({song:{id:i+10,type:'audio'}}))})).length,12);
policy.reset();assert.equal(policy.enabled,false);
console.log('Autoplay policy: opt-in, distinct bounded candidates, no-match/offline/failure, disable and ownership passed.');
