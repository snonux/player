import assert from 'node:assert/strict';
import { loudnessSettings, sameAlbum, replayGain } from '../replay-gain.js';
assert.deepEqual(loudnessSettings(null), { mode: 'off', preamp: 0, untagged: 0 });
assert.deepEqual(loudnessSettings({ mode: 'bad', preamp: 90, untagged: -90 }), { mode: 'off', preamp: 12, untagged: -12 });
const music = { album: 'A', album_artist: 'Artist', replaygain_track_gain_db: -8, replaygain_album_gain_db: -4, replaygain_track_peak: 0.5, replaygain_album_peak: 0.8 };
assert.equal(replayGain(music, {mode:'off',preamp:12}).multiplier, 1);
assert.equal(replayGain(music, {mode:'track',preamp:2}).db, -6);
assert.equal(replayGain(music, {mode:'album'}).db, -4);
assert.equal(replayGain(music, {mode:'automatic'}, true).db, -4);
assert.equal(replayGain(music, {mode:'automatic'}, false).db, -8);
const boosted = replayGain({...music,replaygain_track_gain_db:12}, {mode:'track'});
assert(Math.abs(boosted.db - 6.020599913) < 0.00001);
assert(boosted.multiplier * music.replaygain_track_peak <= 1.000001);
assert.equal(replayGain({replaygain_track_gain_db:9}, {mode:'track'}).db, 0);
assert.equal(replayGain(null, {mode:'track',untagged:12}).db, 0);
assert.equal(replayGain(null, {mode:'album',untagged:-5,preamp:12}).db, -5);
assert.equal(replayGain({replaygain_track_gain_db:NaN}, {mode:'track'}).db, 0);
assert.equal(replayGain({...music,replaygain_track_peak:2}, {mode:'track',preamp:12}).db, -20 * Math.log10(2));
assert(sameAlbum([{music},{music:{...music,title:'Other'}}]));
assert(!sameAlbum([{music}]));
assert(!sameAlbum([{music},{music:{...music,album_artist:'Other'}}]));
assert(!sameAlbum([{},{}]));
console.log('ReplayGain mode selection, conservative missing-tag policy and peak headroom passed.');

const releaseA = '12345678-abcd-1234-abcd-123456789abc';
const releaseB = '12345678-abcd-1234-abcd-123456789abd';
assert(!sameAlbum([{music:{...music,release_mbid:releaseA}},{music:{...music,release_mbid:releaseB}}]));
assert(sameAlbum([{music:{release_mbid:releaseA}},{music:{release_mbid:` ${releaseA.toUpperCase()} `}}]));
assert(sameAlbum([{music:{album:'Compilation',compilation:true,artist:'One'}},{music:{album:'Compilation',compilation:true,artist:'Two'}}]));
assert(sameAlbum([{music:{album:' A  Name ',album_artist:' ARTIST  Name '}},{music:{album:'a name',album_artist:'artist name'}}]));
assert(!sameAlbum([{music:{album:'A',release_mbid:'invalid'}},{music:{album:'A',release_mbid:'invalid'}}]));
console.log('Automatic loudness uses canonical release MBIDs, compilation identity and normalized album text.');
